import { chromium } from 'playwright-core';
const b = await chromium.connectOverCDP('http://127.0.0.1:9222');
const page = b.contexts()[0].pages().find(p => p.url().includes('index.html'));
const s = await page.context().newCDPSession(page);
await s.send('Emulation.setDeviceMetricsOverride', { width: 1520, height: 1400, deviceScaleFactor: 1, mobile: false });
await page.reload({ waitUntil: 'domcontentloaded' });
await page.waitForTimeout(6000);
await page.getByText('Souvenirs', { exact: true }).first().click();
await page.waitForTimeout(3000);
const radii = await page.evaluate(()=>{const o=[];document.querySelectorAll('img').forEach(i=>{const w=i.parentElement,r=w.getBoundingClientRect();if(r.width<0.5)return;o.push(getComputedStyle(w).borderRadius+' @'+Math.round(r.width));});return [...new Set(o)];});
console.log('RADII:', JSON.stringify(radii));
await page.screenshot({ path: process.argv[2] });
await b.close();
